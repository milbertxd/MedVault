exports.getForecast60Day = async (req, res) => {
  try {
    const horizonDays = 60;
    const now = new Date();
    const fromDate = new Date(now);
    fromDate.setDate(fromDate.getDate() - horizonDays);

    const medicineQuery = { isActive: true };
    if (!hasCentralReadAccess(req.user.role)) {
      medicineQuery.healthCenter = req.user.healthCenter._id;
    } else if (req.query.healthCenter) {
      medicineQuery.healthCenter = req.query.healthCenter;
    }

    const medicines = await Medicine.find(medicineQuery)
      .select("name category quantity minimumStock unit healthCenter")
      .populate("healthCenter", "name barangay");

    const medicineIds = medicines.map((m) => m._id);
    const usageAgg = await DispensingHistory.aggregate([
      {
        $match: {
          medicine: { $in: medicineIds },
          createdAt: { $gte: fromDate },
        },
      },
      {
        $group: {
          _id: "$medicine",
          totalDispensed: { $sum: "$quantity" },
          txCount: { $sum: 1 },
          lastDispensedAt: { $max: "$createdAt" },
        },
      },
    ]);

    const usageMap = new Map(usageAgg.map((row) => [String(row._id), row]));

    const forecasts = medicines.map((med) => {
      const usage = usageMap.get(String(med._id));
      const totalDispensed = usage?.totalDispensed || 0;
      const movingAveragePerDay = Number((totalDispensed / horizonDays).toFixed(2));
      const daysUntilStockout = movingAveragePerDay > 0
        ? Number((med.quantity / movingAveragePerDay).toFixed(1))
        : null;

      return {
        medicineId: med._id,
        medicineName: med.name,
        category: med.category,
        healthCenter: med.healthCenter,
        currentQuantity: med.quantity,
        minimumStock: med.minimumStock,
        unit: med.unit,
        movingAverage60Day: movingAveragePerDay,
        totalDispensed60Day: totalDispensed,
        transactions60Day: usage?.txCount || 0,
        lastDispensedAt: usage?.lastDispensedAt || null,
        projectedDaysUntilStockout: daysUntilStockout,
      };
    });

    forecasts.sort((a, b) => {
      if (a.projectedDaysUntilStockout == null) return 1;
      if (b.projectedDaysUntilStockout == null) return -1;
      return a.projectedDaysUntilStockout - b.projectedDaysUntilStockout;
    });

    res.json({
      horizonDays,
      forecasts,
      generatedAt: new Date().toISOString(),
    });
  } catch (error) {
    if (process.env.NODE_ENV !== "production") {
      console.error("Get forecast error:", error);
    }
    res.status(500).json({ message: "Failed to retrieve forecast" });
  }
};

exports.generateLogsReport = async (req, res) => {
  try {
    const { action, startDate, endDate } = req.query;
    const query = {};

    if (!hasCentralReadAccess(req.user.role)) {
      query.healthCenter = req.user.healthCenter._id;
    } else if (req.query.healthCenter) {
      query.healthCenter = req.query.healthCenter;
    }

    if (action) query.action = action;
    if (startDate || endDate) {
      query.createdAt = {};
      if (startDate) query.createdAt.$gte = new Date(startDate);
      if (endDate) query.createdAt.$lte = new Date(endDate);
    }

    const dispensingQuery = { ...query };
    delete dispensingQuery.action;

    const [auditLogs, dispensingRecords] = await Promise.all([
      AuditLog.find(query)
        .populate("user", "firstName lastName")
        .populate("healthCenter", "name barangay")
        .sort({ createdAt: -1 })
        .limit(500),
      DispensingHistory.find(dispensingQuery)
        .populate("medicine", "name category unit")
        .populate("dispensedBy", "firstName lastName")
        .populate("healthCenter", "name barangay")
        .sort({ createdAt: -1 })
        .limit(500),
    ]);

    const doc = new PDFDocument({ margin: 40, size: "A4", layout: "landscape" });

    res.setHeader("Content-Type", "application/pdf");
    res.setHeader(
      "Content-Disposition",
      `attachment; filename=logs-report-${new Date().toISOString().split("T")[0]}.pdf`
    );

    doc.pipe(res);

    doc.font("Helvetica-Bold").fontSize(16).text("COMPLIANCE LOGS REPORT", { align: "center" });
    doc.moveDown(0.3);
    doc.font("Helvetica").fontSize(9).text(`Generated: ${new Date().toLocaleString("en-PH")}`, { align: "center" });
    doc.text(`Prepared by: ${req.user.firstName} ${req.user.lastName}`, { align: "center" });
    doc.moveDown(1);

    doc.font("Helvetica-Bold").fontSize(11).text("Section A: Audit Trail");
    doc.moveDown(0.3);

    const auditHeaders = ["Date/Time", "Action", "Description", "User", "Center"];
    const auditWidths = [120, 120, 280, 110, 140];

    let x = 40;
    let y = doc.y;
    doc.font("Helvetica-Bold").fontSize(8);
    auditHeaders.forEach((header, i) => {
      doc.text(header, x, y, { width: auditWidths[i] });
      x += auditWidths[i];
    });
    y += 14;
    doc.moveTo(40, y).lineTo(40 + auditWidths.reduce((a, b) => a + b, 0), y).stroke();
    y += 4;

    doc.font("Helvetica").fontSize(7);
    for (const log of auditLogs) {
      if (y > 520) {
        doc.addPage();
        y = 40;
      }
      const row = [
        new Date(log.createdAt).toLocaleString("en-PH"),
        log.action,
        log.description,
        log.user ? `${log.user.firstName} ${log.user.lastName}` : "System",
        log.healthCenter?.name || "-",
      ];
      x = 40;
      row.forEach((cell, i) => {
        doc.text(String(cell), x, y, { width: auditWidths[i], ellipsis: true });
        x += auditWidths[i];
      });
      y += 13;
    }

    if (y > 470) {
      doc.addPage();
      y = 40;
    } else {
      y += 20;
    }

    doc.font("Helvetica-Bold").fontSize(11).text("Section B: QR Dispensing Records", 40, y);
    y += 18;

    const dispHeaders = ["Date/Time", "Medicine", "Program", "Qty", "Staff", "Center"];
    const dispWidths = [120, 220, 140, 70, 120, 140];
    x = 40;
    doc.font("Helvetica-Bold").fontSize(8);
    dispHeaders.forEach((header, i) => {
      doc.text(header, x, y, { width: dispWidths[i] });
      x += dispWidths[i];
    });
    y += 14;
    doc.moveTo(40, y).lineTo(40 + dispWidths.reduce((a, b) => a + b, 0), y).stroke();
    y += 4;

    doc.font("Helvetica").fontSize(7);
    for (const rec of dispensingRecords) {
      if (y > 520) {
        doc.addPage();
        y = 40;
      }
      const row = [
        new Date(rec.createdAt).toLocaleString("en-PH"),
        rec.medicine?.name || "Unknown",
        rec.medicine?.category || "-",
        `${rec.quantity} ${rec.medicine?.unit || "pcs"}`,
        rec.dispensedBy ? `${rec.dispensedBy.firstName} ${rec.dispensedBy.lastName}` : "-",
        rec.healthCenter?.name || "-",
      ];
      x = 40;
      row.forEach((cell, i) => {
        doc.text(String(cell), x, y, { width: dispWidths[i], ellipsis: true });
        x += dispWidths[i];
      });
      y += 13;
    }

    doc.end();

    await createAuditLog({
      action: "REPORT_GENERATED",
      description: "Generated compliance logs PDF report",
      user: req.user._id,
      healthCenter: req.user.healthCenter._id,
      ipAddress: req.ip,
    });
  } catch (error) {
    if (process.env.NODE_ENV !== "production") {
      console.error("Generate logs report error:", error);
    }
    res.status(500).json({ message: "Failed to generate logs report" });
  }
};
